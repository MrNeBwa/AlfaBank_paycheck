namespace AlfaBank.App.Infrastructure;

/// <summary>
/// Характер сообщения, выводимого под формой или таблицей.
/// Определяет цвет сообщения: нейтральный, положительный или отрицательный.
/// </summary>
public enum StatusMessageKind
{
    /// <summary>
    /// Нейтральное сообщение: справочная информация, составленная без оценки.
    /// </summary>
    Info = 0,

    /// <summary>
    /// Положительный результат: действие выполнено успешно.
    /// </summary>
    Success = 1,

    /// <summary>
    /// Отрицательный результат: ошибка либо неблагоприятный исход.
    /// </summary>
    Error = 2
}
